/** One catalog item that can be tracked in the usage log. */
export interface Equipment {
  id: string;
  name: string;
  created_at?: string;
}

/** One recorded equipment usage session. */
export interface EquipmentUsage {
  id: string;
  user_id: string;
  equipment_id: string;
  started_at: string; // ISO timestamp
  ended_at: string; // ISO timestamp
  duration_minutes: number;
  remarks: string | null;
  /** Who recorded the entry (a Head), for accountability. */
  logged_by: string | null;
  /** Set when the booking was cancelled — a cancelled row no longer
   *  blocks availability but stays in the history. */
  cancelled_at?: string | null;
  created_at?: string;
}
