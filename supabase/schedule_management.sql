-- =====================================================================
-- SCHEDULE MANAGEMENT MIGRATION
-- Run in Supabase → SQL Editor → New query → paste → Run.
-- Re-runnable and purely additive — no DROP statements, so Supabase
-- won't raise its "destructive operations" warning.
--
-- Delivers the availability/schedule feature end to end:
--   1. public.availability      — the schedule table (single source
--      of truth; replaces the temporary file fallback the code used
--      while this migration was missing)
--   2. status + series_id       — explicit "unavailable" markers and
--      recurring-weekly series grouping
--   3. overlap prevention       — a database constraint that rejects a
--      person's overlapping periods even under simultaneous requests
--   4. indexes + realtime       — fast month queries and live updates
--      for the Head schedule calendar
--   5. role sync                — Heads carry role 'head' so the Head
--      Dashboard and its permissions resolve from role
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. AVAILABILITY TABLE
--    One row per person, per date, per time period. A person can have
--    several rows on the same date (e.g. 08:00–12:00 and 14:00–17:00).
--    Dates are plain `date` and times plain `time`, so every value is
--    stored and read in the same local timezone as the rest of the app.
-- ---------------------------------------------------------------------
create table if not exists public.availability (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null references public.profiles(id) on delete cascade,
  date date not null,
  start_time time not null,
  end_time time not null,
  notes text,
  -- 'available' = the person can work the period;
  -- 'unavailable' = they explicitly marked it (different from no row).
  status text not null default 'available'
    check (status in ('available', 'unavailable')),
  -- Rows generated by one "repeat weekly" request share a series id,
  -- so the UI can label and delete the series as a unit.
  series_id uuid,
  -- Generated half-open tsrange over date+times; the overlap
  -- constraint (section 2) is keyed on it.
  period tsrange generated always as (
    tsrange((date + start_time)::timestamp, (date + end_time)::timestamp)
  ) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint availability_valid_range check (end_time > start_time)
);

-- Existing installs gain the new columns here (guarded + idempotent).
alter table public.availability
  add column if not exists status text not null default 'available'
    check (status in ('available', 'unavailable'));

alter table public.availability
  add column if not exists series_id uuid;

alter table public.availability enable row level security;

-- Row Level Security — mirrors the existing rules: a person manages
-- only their own schedule; Heads can view everyone's.
do $$
begin
  create policy "Users can view their own availability"
    on public.availability for select
    using (auth.uid() = employee_id);
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create policy "Heads can view all availability"
    on public.availability for select
    using (public.is_admin());
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create policy "Users can insert their own availability"
    on public.availability for insert
    with check (auth.uid() = employee_id);
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create policy "Users can update their own availability"
    on public.availability for update
    using (auth.uid() = employee_id)
    with check (auth.uid() = employee_id);
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create policy "Users can delete their own availability"
    on public.availability for delete
    using (auth.uid() = employee_id);
exception
  when duplicate_object then null;
end
$$;

-- ---------------------------------------------------------------------
-- 2. OVERLAP PREVENTION (per person)
--    Different people MAY overlap (several people can be available at
--    the same time) — the constraint is keyed on employee_id, so only
--    the SAME person's overlapping periods are rejected. `period` is a
--    generated half-open tsrange, so back-to-back periods
--    (08:00–12:00 and 12:00–16:00) are legal. Because the rule lives in
--    the database, simultaneous submissions cannot both win.
--    NOTE: overnight (past-midnight) periods are not representable in
--    the existing date+time schema and remain unsupported, matching the
--    existing system.
-- ---------------------------------------------------------------------

-- Generated range over the date + times (immutable expression).
alter table public.availability
  add column if not exists period tsrange
  generated always as (
    tsrange((date + start_time)::timestamp, (date + end_time)::timestamp)
  ) stored;

-- gist support for the uuid equality operator inside the constraint.
create extension if not exists btree_gist;

do $$
begin
  -- Guard on the catalog so a re-run is a true no-op. The exception
  -- handler also catches 42P07 (duplicate_table): an exclusion
  -- constraint is backed by an index, so a partial/earlier run can leave
  -- relation "availability_no_person_overlap" behind, and Postgres then
  -- fails while creating that index — surfacing as duplicate_table, not
  -- duplicate_object.
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.availability'::regclass
      and conname = 'availability_no_person_overlap'
  ) then
    begin
      alter table public.availability
        add constraint availability_no_person_overlap
        exclude using gist (employee_id with =, period with &&);
    exception
      when duplicate_table then null;
      when duplicate_object then null;
    end;
  end if;
end
$$;

-- ---------------------------------------------------------------------
-- 3. INDEXES + REALTIME
-- ---------------------------------------------------------------------
create index if not exists idx_availability_employee_date
  on public.availability (employee_id, date);

create index if not exists idx_availability_date_start
  on public.availability (date, start_time);

create index if not exists idx_availability_series
  on public.availability (series_id)
  where series_id is not null;

-- The Head schedule calendar subscribes to realtime so a change
-- made from a dashboard shows up immediately.
do $$
begin
  alter publication supabase_realtime add table public.availability;
exception
  when duplicate_object then null;
end
$$;

-- ---------------------------------------------------------------------
-- 4. ROLE SYNC
--    Role determines the dashboard and permissions: Heads carry role
--    'head' to reach the Head Dashboard. Idempotent, and it only touches
--    Head rows.
-- ---------------------------------------------------------------------
update public.profiles
  set role = 'head'
  where position in ('admin', 'head')
    and role <> 'head';
