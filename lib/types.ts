export type Role = "head" | "staff";
export type OutputStatus = "pending" | "checking" | "done" | "rejected";
export type AttachmentType = "file" | "link" | "image" | "written";
export type DayStatus = "present" | "unverified" | "incomplete" | "absent";

// Head dashboard additions
export type ProjectStatus = "pending" | "checking" | "approved" | "rejected";
export type ThemePreference = "light" | "dark";

export interface Profile {
  id: string;
  full_name: string | null;
  position: string | null;
  role: Role;
  /** Weekly requirement in hours, e.g. 40. Credits come from days with a submitted output. */
  required_weekly_hours: number;
  email?: string | null;
  profile_picture_url?: string | null;
  theme_preference?: ThemePreference;
}

export interface Session {
  id: string;
  employee_id: string;
  time_in: string; // ISO timestamp
  time_out: string | null; // null = still clocked in
}

/** One persisted calendar day of attendance for a single employee. */
export interface AttendanceDay {
  employee_id: string;
  date: string; // YYYY-MM-DD
  hours: number;
  session_count: number;
  first_in: string | null;
  last_out: string | null;
  has_open_session: boolean;
}

/** A day of attendance plus whether it is creditable (attendance_day_status view). */
export interface AttendanceDayStatus extends AttendanceDay {
  /** True when any output was submitted for this day, whatever its review status. */
  has_output?: boolean;
  /** True only when at least one output on this day was approved. */
  has_approved_output: boolean;
  is_credited: boolean;
}

/** One row of employee_week_hours — the two hour totals per employee per week. */
export interface WeekHours {
  employee_id: string;
  week_start: string; // YYYY-MM-DD (Monday)
  attendance_hours: number;
  credited_hours: number;
  attendance_days: number;
  credited_days: number;
}

export interface Output {
  id: string;
  employee_id: string;
  date: string; // YYYY-MM-DD
  title: string | null;
  attachment_type: AttachmentType;
  /** null for a 'written' submission — there is no file or URL to point at. */
  attachment_url: string | null;
  /** The written body. Plain text only; never HTML. */
  content?: string | null;
  /** The staff member's note to the reviewer (separate from reviewer_notes). */
  submission_notes?: string | null;
  /** Object path inside the 'project-files' bucket, for file/image uploads. */
  storage_path?: string | null;
  /** Original filename of the uploaded file, when there was one. */
  file_name?: string | null;
  /** MIME type reported at upload time. */
  file_mime_type?: string | null;
  /** Uploaded size in bytes. */
  file_size?: number | null;
  status: OutputStatus;
  reviewer_notes: string | null;
  reviewed_by?: string | null;
  reviewed_at?: string | null;
  created_at?: string;
  reviewer?: { full_name: string | null } | null;
}

/** The linked `outputs` row behind a mirrored project review entry. */
export interface ProjectSubmission {
  attachment_type: AttachmentType;
  content: string | null;
  submission_notes: string | null;
  file_name: string | null;
  storage_path: string | null;
  file_mime_type: string | null;
  file_size: number | null;
}

export interface Project {
  id: string;
  title: string;
  description: string | null;
  /** null for a written submission — the body lives on the linked output. */
  file_url: string | null;
  status: ProjectStatus;
  submitted_by: string;
  reviewed_by: string | null;
  reviewer_notes: string | null;
  created_at: string;
  updated_at: string;
  source_output_id?: string | null;
  // Joined fields (from `sender:profiles!...` / `reviewer:profiles!...`)
  submitter?: { full_name: string | null; position: string | null } | null;
  reviewer?: { full_name: string | null } | null;
  /** Joined from the linked outputs row (written body, type, filename). */
  submission?: ProjectSubmission | null;
}

export interface Notification {
  id: string;
  sender_id: string;
  receiver_id: string;
  message: string;
  project_id: string | null;
  is_read: boolean;
  created_at: string;
  // Joined fields (from `sender:profiles!...` / `project:projects(...)`)
  sender?: { full_name: string | null } | null;
  project?: { id: string; title: string; status: ProjectStatus } | null;
}

export interface Availability {
  id: string;
  employee_id: string;
  date: string; // YYYY-MM-DD
  start_time: string; // HH:mm or HH:mm:ss
  end_time: string; // HH:mm or HH:mm:ss
  notes?: string | null;
  /** 'available' (can work) or 'unavailable' (explicitly marked). */
  status?: "available" | "unavailable";
  /** Set when the row was generated by a repeat-weekly request. */
  series_id?: string | null;
  created_at?: string;
  updated_at?: string;
}

/** An availability row plus the owner's name/position (Head views). */
export interface AvailabilityWithProfile extends Availability {
  profile?: { full_name: string | null; position: string | null } | null;
}

